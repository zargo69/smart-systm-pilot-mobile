create table if not exists public.ssp_app_records (
  id bigint generated by default as identity primary key,
  company_id uuid not null references public.ssp_companies(id) on delete cascade,
  collection text not null check (length(trim(collection)) between 1 and 80),
  record_id text not null check (length(trim(record_id)) between 1 and 180),
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  version bigint not null default 1 check (version >= 1),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null,
  deleted_at timestamptz,
  constraint ssp_app_records_company_collection_record_key
    unique (company_id, collection, record_id)
);

create index if not exists ssp_app_records_company_collection_idx
  on public.ssp_app_records (company_id, collection)
  where deleted_at is null;
create index if not exists ssp_app_records_updated_at_idx
  on public.ssp_app_records (company_id, updated_at desc);

alter table public.ssp_app_records enable row level security;

drop policy if exists ssp_app_records_select_member on public.ssp_app_records;
create policy ssp_app_records_select_member
  on public.ssp_app_records for select to authenticated
  using (public.ssp_is_company_member(company_id));

drop policy if exists ssp_app_records_insert_member on public.ssp_app_records;
create policy ssp_app_records_insert_member
  on public.ssp_app_records for insert to authenticated
  with check (
    public.ssp_is_company_member(company_id)
    and updated_by = auth.uid()
  );

drop policy if exists ssp_app_records_update_member on public.ssp_app_records;
create policy ssp_app_records_update_member
  on public.ssp_app_records for update to authenticated
  using (public.ssp_is_company_member(company_id))
  with check (
    public.ssp_is_company_member(company_id)
    and updated_by = auth.uid()
  );

drop policy if exists ssp_app_records_delete_member on public.ssp_app_records;
create policy ssp_app_records_delete_member
  on public.ssp_app_records for delete to authenticated
  using (public.ssp_is_company_member(company_id));

create or replace function public.ssp_save_record(
  p_company_id uuid,
  p_collection text,
  p_record_id text,
  p_payload jsonb,
  p_expected_version bigint default 0
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  saved_version bigint;
begin
  if auth.uid() is null then raise exception 'Connexion requise'; end if;
  if not public.ssp_is_company_member(p_company_id) then raise exception 'Accès refusé'; end if;
  if p_collection is null or length(trim(p_collection)) not between 1 and 80
     or p_record_id is null or length(trim(p_record_id)) not between 1 and 180 then
    raise exception 'Collection ou identifiant invalide';
  end if;
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'Contenu JSON invalide';
  end if;
  if p_expected_version is null or p_expected_version < 0 then
    raise exception 'Version attendue invalide';
  end if;

  if p_expected_version = 0 then
    insert into public.ssp_app_records
      (company_id, collection, record_id, payload, version, updated_at, updated_by, deleted_at)
    values
      (p_company_id, trim(p_collection), trim(p_record_id), p_payload, 1, now(), auth.uid(), null)
    on conflict (company_id, collection, record_id) do nothing
    returning version into saved_version;
  else
    update public.ssp_app_records
       set payload = p_payload, version = version + 1,
           updated_at = now(), updated_by = auth.uid(), deleted_at = null
     where company_id = p_company_id and collection = trim(p_collection)
       and record_id = trim(p_record_id) and version = p_expected_version
    returning version into saved_version;
  end if;

  if saved_version is null then
    raise exception 'SSP_CONFLICT: version distante différente. Rechargez avant de réessayer.';
  end if;
  return saved_version;
end;
$$;

create or replace function public.ssp_soft_delete_record(
  p_company_id uuid,
  p_collection text,
  p_record_id text,
  p_expected_version bigint
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  saved_version bigint;
begin
  if auth.uid() is null then raise exception 'Connexion requise'; end if;
  if not public.ssp_is_company_member(p_company_id) then raise exception 'Accès refusé'; end if;
  if p_expected_version is null or p_expected_version < 1 then
    raise exception 'Version attendue invalide';
  end if;

  update public.ssp_app_records
     set version = version + 1, updated_at = now(),
         updated_by = auth.uid(), deleted_at = now()
   where company_id = p_company_id and collection = trim(p_collection)
     and record_id = trim(p_record_id) and version = p_expected_version
     and deleted_at is null
  returning version into saved_version;

  if saved_version is null then
    raise exception 'SSP_CONFLICT: suppression concurrente ou fiche introuvable.';
  end if;
  return saved_version;
end;
$$;

revoke all on function public.ssp_save_record(uuid, text, text, jsonb, bigint) from public, anon;
revoke all on function public.ssp_soft_delete_record(uuid, text, text, bigint) from public, anon;
grant execute on function public.ssp_save_record(uuid, text, text, jsonb, bigint) to authenticated;
grant execute on function public.ssp_soft_delete_record(uuid, text, text, bigint) to authenticated;

